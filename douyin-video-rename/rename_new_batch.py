def main():
    from common import probe_wh, probe_duration

    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    plan = []
    for old, meaning in PAIRS:
        wh = probe_wh(os.path.join(DL, old))
        if not wh:
            print(f'跳过(读不到分辨率): {old}')
            continue
        w, h = wh
        new = f'{meaning[:-4]}_{w}x{h}.mp4'
        plan.append((old, new, w, h, probe_duration(os.path.join(DL, old)) or 0.0))

    errors = []
    for old, new, *_ in plan:
        if not os.path.exists(os.path.join(DL, old)):
            errors.append(f'源文件不存在: {old}')
        if os.path.exists(os.path.join(DL, new)):
            errors.append(f'目标已存在: {new}')
    if len({n for _, n, *_ in plan}) != len(plan):
        errors.append('目标重名冲突')
    if errors:
        print('中止:')
        for e in errors:
            print(' ', e)
        return

    # 追加记录
    with open(RECORD, 'a', encoding='utf-8') as fh:
        fh.write('\n' + '=' * 40 + '\n')
        fh.write(f'第二批重命名时间: {datetime.datetime.now().isoformat(timespec="seconds")}\n')
        fh.write('匹配方式: 视频 8 帧均匀采样感知哈希(全部 8/8 帧一致, 最小距离 0-1) + 时长一致(±0.1s)\n')
        fh.write(f'数量: {len(plan)} 个文件\n\n')
        fh.write('序号\t原文件名\t新文件名\t分辨率\t时长(秒)\n')
        for i, (old, new, w, h, d) in enumerate(plan, 1):
            fh.write(f'{i}\t{old}\t{new}\t{w}x{h}\t{d:.1f}\n')

    for old, new, *_ in plan:
        os.rename(os.path.join(DL, old), os.path.join(DL, new))
        print(f'renamed: {old} -> {new}')

    print(f'\n记录已追加: {RECORD}')

import sys
if __name__ == '__main__':
    main()
